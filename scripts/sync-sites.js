#!/usr/bin/env node
// Builds apps/extension/sites/adapters.js from the site adapters,
// apps/extension/sites/*.json (PLAN.md Step 15). The content script and the
// popup load it as a plain script: no fetch. Each adapter is checked first;
// a bad one stops the build.
//
// Run after editing an adapter:  node scripts/sync-sites.js
// sites.test.js fails when adapters.js is stale.
'use strict';

const fs = require('node:fs');
const path = require('node:path');

const root = path.join(__dirname, '..');
const SITES_DIR = path.join(root, 'apps', 'extension', 'sites');
const OUTPUT = path.join(SITES_DIR, 'adapters.js');

const SELECTOR_KEYS = ['composer', 'sendButton', 'stopButton', 'userMessage', 'assistantMessage', 'picker', 'effortToggle'];
const KEYS = ['site', 'hosts', ...SELECTOR_KEYS, 'insertStrategy', 'lastVerified', 'notes'];
// How Step 23 puts text into the composer: a textarea's value, the editor's
// own insertText command, or a synthetic paste for editors that ignore it.
const INSERT_STRATEGIES = ['value', 'insertText', 'paste'];

/** Brackets, parentheses and quotes that close: the syntax a typo breaks. */
function selectorLooksValid(selector) {
  const close = { '[': ']', '(': ')' };
  const stack = [];
  let quote = null;
  for (const ch of selector) {
    if (quote) {
      if (ch === quote) quote = null;
      continue;
    }
    if (ch === '"' || ch === "'") quote = ch;
    else if (close[ch]) stack.push(close[ch]);
    else if (ch === ']' || ch === ')') {
      if (stack.pop() !== ch) return false;
    }
  }
  return !quote && stack.length === 0 && !/(^|,)\s*(,|$)/.test(selector);
}

/** What is wrong with an adapter, as a list of messages; empty when it is fine. */
function adapterProblems(adapter, now = new Date()) {
  const problems = [];
  if (!adapter || typeof adapter !== 'object' || Array.isArray(adapter)) return ['not an object'];
  for (const key of Object.keys(adapter)) {
    if (!KEYS.includes(key)) problems.push(`unknown key "${key}"`);
  }
  for (const key of KEYS) {
    if (!(key in adapter)) problems.push(`missing "${key}"`);
  }
  if (typeof adapter.site !== 'string' || !adapter.site.trim()) problems.push('site must name the site');
  if (!Array.isArray(adapter.hosts) || !adapter.hosts.length ||
      !adapter.hosts.every((h) => typeof h === 'string' && /^[a-z0-9.-]+$/.test(h))) {
    problems.push('hosts must be a list of lower-case hostnames');
  }
  for (const key of SELECTOR_KEYS) {
    const value = adapter[key];
    if (value === null && key !== 'composer') continue;
    if (typeof value !== 'string' || !value.trim()) problems.push(`${key} must be a CSS selector${key === 'composer' ? '' : ' or null'}`);
    else if (!selectorLooksValid(value)) problems.push(`${key} is not a well-formed selector: ${value}`);
  }
  if (!INSERT_STRATEGIES.includes(adapter.insertStrategy)) {
    problems.push(`insertStrategy must be one of ${INSERT_STRATEGIES.join(', ')}`);
  }
  if (adapter.lastVerified !== null) {
    const ok = typeof adapter.lastVerified === 'string' && /^\d{4}-\d{2}-\d{2}$/.test(adapter.lastVerified) &&
      !Number.isNaN(Date.parse(adapter.lastVerified));
    if (!ok) problems.push('lastVerified must be null or a YYYY-MM-DD date');
    else if (Date.parse(adapter.lastVerified) > now.getTime()) problems.push('lastVerified is in the future');
  }
  if (typeof adapter.notes !== 'string') problems.push('notes must be a string');
  return problems;
}

/** Every adapter, by file name order. Throws on a bad one or a host two adapters claim. */
function readAdapters(dir = SITES_DIR) {
  const files = fs.readdirSync(dir).filter((f) => f.endsWith('.json')).sort();
  const adapters = [];
  const claimed = new Map();
  for (const file of files) {
    const adapter = JSON.parse(fs.readFileSync(path.join(dir, file), 'utf8'));
    const problems = adapterProblems(adapter);
    if (problems.length) throw new Error(`sites/${file}: ${problems.join('; ')}`);
    for (const host of adapter.hosts) {
      if (claimed.has(host)) throw new Error(`sites/${file}: host ${host} is already in sites/${claimed.get(host)}`);
      claimed.set(host, file);
    }
    adapters.push(adapter);
  }
  return adapters;
}

function buildAdapters(adapters = readAdapters()) {
  return [
    '// EcoPrompt Coach site adapters — GENERATED by scripts/sync-sites.js from',
    '// apps/extension/sites/*.json. Do not edit; edit the JSON and run the script.',
    "'use strict';",
    '',
    `globalThis.EcoPromptSiteAdapters = Object.freeze(JSON.parse(${JSON.stringify(JSON.stringify(adapters))}));`,
    ''
  ].join('\n');
}

module.exports = { SITES_DIR, OUTPUT, KEYS, SELECTOR_KEYS, INSERT_STRATEGIES, selectorLooksValid, adapterProblems, readAdapters, buildAdapters };

if (require.main === module) {
  const adapters = readAdapters();
  fs.writeFileSync(OUTPUT, buildAdapters(adapters));
  console.log(`synced ${adapters.length} site adapters -> ${path.relative(root, OUTPUT)}`);
}
