#!/usr/bin/env node
// Builds what the apps load from the shared core (PLAN.md Step 13):
//
//   packages/core/src/data/precomputed.json  each model's coefficients, worked
//       out once from the catalog, so no surface fits at start-up
//   apps/<app>/vendor/core.bundle.js  the core's scripts, its data inlined and
//       the precomputed coefficients, in one plain script: no fetch at
//       start-up, and it works from file://
//
// The extension and web app load the bundle as a plain script — no bundler.
// Run after any change in packages/core:  node scripts/sync-core.js
// core.test.js fails when either output is stale.
'use strict';

const fs = require('node:fs');
const path = require('node:path');

const root = path.join(__dirname, '..');
const coreSrc = path.join(root, 'packages', 'core', 'src');
const PRECOMPUTED = path.join(coreSrc, 'data', 'precomputed.json');
const BUNDLE = 'core.bundle.js';
const targets = [
  path.join(root, 'apps', 'extension', 'vendor'),
  path.join(root, 'apps', 'web', 'vendor')
];

// The engine first; the rest in name order. Every script in core/src ships
// except index.js (the Node entry point, which uses require()). Globbing
// means a newly added core file can't be silently left out of the apps.
function coreScripts() {
  const rest = fs.readdirSync(coreSrc)
    .filter((f) => f.endsWith('.js') && f !== 'index.js' && f !== 'calculator.js')
    .sort();
  return ['calculator.js', ...rest];
}

function readJson(name) {
  return JSON.parse(fs.readFileSync(path.join(coreSrc, 'data', name), 'utf8'));
}

/** precompute() over a freshly fitted engine: never over a precomputed one. */
function buildPrecomputed() {
  const { ImpactEngine, precompute } = require(path.join(coreSrc, 'calculator.js'));
  const engine = new ImpactEngine({ models: readJson('models.json'), grids: readJson('grids.json') });
  return precompute(engine);
}

function precomputedText(precomputed) {
  return JSON.stringify(precomputed, null, 2) + '\n';
}

function buildBundle(precomputed) {
  // JSON.parse of a string literal parses faster than an object literal.
  const inline = (value) => `JSON.parse(${JSON.stringify(JSON.stringify(value))})`;
  const parts = [
    '// EcoPrompt Coach core bundle — GENERATED by scripts/sync-core.js from',
    '// packages/core. Do not edit; edit packages/core and run the script.',
    ''
  ];
  for (const f of coreScripts()) {
    parts.push(`// ---- ${f} ----`, fs.readFileSync(path.join(coreSrc, f), 'utf8').trimEnd(), '');
  }
  parts.push(
    '// ---- data and precomputed coefficients ----',
    '(function (root) {',
    '  const Core = root.EcoPromptCore;',
    '  Core.data = {',
    `    models: ${inline(readJson('models.json'))},`,
    `    grids: ${inline(readJson('grids.json'))},`,
    `    equivalents: ${inline(readJson('equivalents.json'))}`,
    '  };',
    `  Core.precomputed = ${inline(precomputed)};`,
    '  /** The engine and converters over the bundled data: no fetch, no fitting. */',
    '  Core.createBundledEngine = function createBundledEngine() {',
    '    const { models, grids, equivalents } = Core.data;',
    '    return {',
    '      engine: new Core.ImpactEngine({ models, grids, equivalents, precomputed: Core.precomputed }),',
    '      converters: Core.createConverters(equivalents)',
    '    };',
    '  };',
    "})(typeof globalThis !== 'undefined' ? globalThis : this);",
    ''
  );
  return parts.join('\n');
}

function sync() {
  const precomputed = buildPrecomputed();
  fs.writeFileSync(PRECOMPUTED, precomputedText(precomputed));
  const bundle = buildBundle(precomputed);
  for (const target of targets) {
    fs.mkdirSync(target, { recursive: true });
    // The bundle replaces the separate scripts and data files.
    for (const entry of fs.readdirSync(target)) {
      if (entry !== BUNDLE) fs.rmSync(path.join(target, entry), { recursive: true, force: true });
    }
    fs.writeFileSync(path.join(target, BUNDLE), bundle);
    console.log(`synced core -> ${path.relative(root, path.join(target, BUNDLE))} (${Math.round(bundle.length / 1024)} KB)`);
  }
}

module.exports = { BUNDLE, PRECOMPUTED, targets, coreScripts, buildPrecomputed, precomputedText, buildBundle };

if (require.main === module) sync();
